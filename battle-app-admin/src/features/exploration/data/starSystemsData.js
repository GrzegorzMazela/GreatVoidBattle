// Pobierz układy według frakcji
export function getSystemsByFaction(factionId) {
  return STAR_SYSTEMS.filter(s => s.faction === factionId);
}

// Pobierz układy znane dla frakcji
export function getKnownSystemsForFaction(factionId) {
  return STAR_SYSTEMS.filter(s => 
    s.knownToAll || 
    s.faction === factionId || 
    (s.knownTo && s.knownTo.includes(factionId))
  );
}

// Pobierz układy stołeczne
export function getCapitalSystems() {
  return STAR_SYSTEMS.filter(s => s.isCapital);
}

